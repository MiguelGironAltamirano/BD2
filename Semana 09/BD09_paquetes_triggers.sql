-- Tablas auxiliares requeridas por el laboratorio
--------------------------------------------------------------------------------

-- HORARIO: día, turno, hora inicio/fin 
CREATE TABLE HORARIO (
  DIA_DE_LA_SEMANA   VARCHAR2(10)   NOT NULL,
  TURNO              VARCHAR2(10)   NOT NULL,
  HORA_INICIO        VARCHAR2(8)    NOT NULL, -- 'HH24:MI:SS'
  HORA_TERMINO       VARCHAR2(8)    NOT NULL, -- 'HH24:MI:SS'
  CONSTRAINT PK_HORARIO PRIMARY KEY (DIA_DE_LA_SEMANA, TURNO)
);

-- EMPLEADO_HORARIO: asignación de horario por empleado
CREATE TABLE EMPLEADO_HORARIO (
  EMPLOYEE_ID        NUMBER         NOT NULL,
  DIA_DE_LA_SEMANA   VARCHAR2(10)   NOT NULL,
  TURNO              VARCHAR2(10)   NOT NULL,
  CONSTRAINT PK_EMPLEADO_HORARIO PRIMARY KEY (EMPLOYEE_ID, DIA_DE_LA_SEMANA, TURNO)
);

-- ASISTENCIA_EMPLEADO: registro de asistencia del empleado
CREATE TABLE ASISTENCIA_EMPLEADO (
  EMPLOYEE_ID        NUMBER         NOT NULL,
  DIA_DE_LA_SEMANA   VARCHAR2(10)   NOT NULL,
  FECHA_REAL         DATE           NOT NULL,
  HORA_INICIO_REAL   TIMESTAMP      NOT NULL,
  HORA_TERMINO_REAL  TIMESTAMP      NOT NULL
);

-- CAPACITACION: catálogo de capacitaciones
CREATE TABLE CAPACITACION (
  CAPACITACION_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE               VARCHAR2(100) NOT NULL,
  HORAS_CAPACITACION   NUMBER        NOT NULL,
  DESCRIPCION          VARCHAR2(4000)
);

-- EMPLEADO_CAPACITACION: relación empleado-capacitación
CREATE TABLE EMPLEADO_CAPACITACION (
  EMPLOYEE_ID       NUMBER        NOT NULL,
  CAPACITACION_ID   NUMBER        NOT NULL,
  CONSTRAINT PK_EMPLEADO_CAP PRIMARY KEY (EMPLOYEE_ID, CAPACITACION_ID),
  CONSTRAINT FK_EMPLEADO_CAP_CAP FOREIGN KEY (CAPACITACION_ID) REFERENCES CAPACITACION(CAPACITACION_ID)
);

-- INASISTENCIAS_LOG: auditoría de registros fuera de la ventana permitida
CREATE TABLE INASISTENCIAS_LOG (
  LOG_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  EMPLOYEE_ID     NUMBER,
  FECHA           DATE,
  HORA_REGISTRO   TIMESTAMP,
  HORA_ESPERADA   VARCHAR2(50),
  DIFERENCIA_MIN  NUMBER,
  MOTIVO          VARCHAR2(200),
  CREADO_EN       DATE DEFAULT SYSDATE
);

