-- trg_validar_asistencia_emp: valida día y correspondencia de horas con el horario
CREATE OR REPLACE TRIGGER trg_validar_asistencia_emp
BEFORE INSERT OR UPDATE ON asistencia_empleado
FOR EACH ROW
DECLARE
  v_weekday_name  VARCHAR2(20);
  v_weekday_num   VARCHAR2(1);
  v_cnt           NUMBER;
  v_inicio_ok     BOOLEAN := FALSE;
  v_termino_ok    BOOLEAN := FALSE;
BEGIN
  v_weekday_name := TRIM(UPPER(TO_CHAR(:NEW.fecha_real,'DAY','NLS_DATE_LANGUAGE=SPANISH')));
  v_weekday_num  := TO_CHAR(:NEW.fecha_real,'D');

  SELECT COUNT(*) INTO v_cnt
  FROM empleado_horario eh
  JOIN horario h ON (eh.dia_de_la_semana = h.dia_de_la_semana AND eh.turno = h.turno)
  WHERE eh.employee_id = :NEW.employee_id
    AND ( UPPER(h.dia_de_la_semana) = v_weekday_name OR h.dia_de_la_semana = v_weekday_num );

  IF v_cnt = 0 THEN
    RAISE_APPLICATION_ERROR(-20020, 'La fecha no corresponde al día del horario asignado.');
  END IF;

  FOR r IN (
    SELECT h.hora_inicio, h.hora_termino
    FROM empleado_horario eh
    JOIN horario h ON (eh.dia_de_la_semana = h.dia_de_la_semana AND eh.turno = h.turno)
    WHERE eh.employee_id = :NEW.employee_id
      AND ( UPPER(h.dia_de_la_semana) = v_weekday_name OR h.dia_de_la_semana = v_weekday_num )
  ) LOOP
    BEGIN
      DECLARE
        v_sched_start DATE;
        v_sched_end   DATE;
        v_reg_start   DATE := CAST(:NEW.hora_inicio_real AS DATE);
        v_reg_end     DATE := CAST(:NEW.hora_termino_real AS DATE);
      BEGIN
        v_sched_start := TO_DATE(TO_CHAR(:NEW.fecha_real,'YYYY-MM-DD')||' '||r.hora_inicio,  'YYYY-MM-DD HH24:MI:SS');
        v_sched_end   := TO_DATE(TO_CHAR(:NEW.fecha_real,'YYYY-MM-DD')||' '||r.hora_termino, 'YYYY-MM-DD HH24:MI:SS');

        IF ABS((v_reg_start - v_sched_start) * 24) <= 1 THEN v_inicio_ok := TRUE; END IF;
        IF ABS((v_reg_end   - v_sched_end  ) * 24) <= 1 THEN v_termino_ok := TRUE; END IF;
      END;
    EXCEPTION
      WHEN OTHERS THEN NULL;
    END;

    IF v_inicio_ok AND v_termino_ok THEN EXIT; END IF;
  END LOOP;

  IF NOT (v_inicio_ok AND v_termino_ok) THEN
    RAISE_APPLICATION_ERROR(-20021, 'Horas reales fuera de tolerancia con el horario asignado.');
  END IF;
END;
/

-- trg_validar_rango_salario: asegura que salary esté dentro del rango de JOBS
CREATE OR REPLACE TRIGGER trg_validar_rango_salario
BEFORE INSERT OR UPDATE ON employees
FOR EACH ROW
DECLARE
  v_min NUMBER;
  v_max NUMBER;
BEGIN
  SELECT min_salary, max_salary INTO v_min, v_max
  FROM jobs WHERE job_id = :NEW.job_id;

  IF :NEW.salary IS NULL THEN
    RAISE_APPLICATION_ERROR(-20030, 'El salario no puede ser NULL.');
  ELSIF :NEW.salary < v_min OR :NEW.salary > v_max THEN
    RAISE_APPLICATION_ERROR(-20031, 'Salario fuera del rango permitido para el puesto.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20032, 'Puesto (job_id) no encontrado en JOBS.');
END;
/

-- trg_registrar_inasistencia: marca en INASISTENCIAS_LOG si ingreso difiere > 30 min
CREATE OR REPLACE TRIGGER trg_registrar_inasistencia
BEFORE INSERT ON asistencia_empleado
FOR EACH ROW
DECLARE
  v_sched_start  DATE;
  v_reg_start    DATE;
  v_diff_min     NUMBER;
BEGIN
  SELECT TO_DATE(TO_CHAR(:NEW.fecha_real,'YYYY-MM-DD')||' '||h.hora_inicio,'YYYY-MM-DD HH24:MI:SS')
  INTO v_sched_start
  FROM empleado_horario eh
  JOIN horario h ON (eh.dia_de_la_semana = h.dia_de_la_semana AND eh.turno = h.turno)
  WHERE eh.employee_id = :NEW.employee_id
    AND (UPPER(h.dia_de_la_semana) = UPPER(TRIM(TO_CHAR(:NEW.fecha_real,'DAY','NLS_DATE_LANGUAGE=SPANISH')))
         OR h.dia_de_la_semana = TO_CHAR(:NEW.fecha_real,'D'))
    AND ROWNUM = 1;

  v_reg_start := CAST(:NEW.hora_inicio_real AS DATE);
  v_diff_min  := (v_reg_start - v_sched_start) * 24 * 60;

  IF ABS(v_diff_min) > 30 THEN
    INSERT INTO inasistencias_log(employee_id, fecha, hora_registro, hora_esperada, diferencia_min, motivo)
    VALUES(:NEW.employee_id, TRUNC(:NEW.fecha_real), SYSTIMESTAMP, TO_CHAR(v_sched_start,'HH24:MI:SS'),
           v_diff_min, 'Registro fuera de ventana +/-30 min');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    NULL;
  WHEN OTHERS THEN
    NULL;
END;
/
