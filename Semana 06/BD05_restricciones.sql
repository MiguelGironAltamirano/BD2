DROP TABLE Persona;
CREATE TABLE Persona (
    idPersona      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(100) NOT NULL,
    apellido       VARCHAR2(100) NOT NULL,
    direccion      VARCHAR2(200),
    telefono       VARCHAR2(20),
    email          VARCHAR2(100),
    CONSTRAINT pk_persona PRIMARY KEY (idPersona)
);
SELECT * FROM Persona;
-- Subtipos

-- Alumno
DROP TABLE Alumno;
CREATE TABLE Alumno (
    idPersona          NUMBER,
    idCentroEducativo  NUMBER NOT NULL,
    numExpediente      VARCHAR2(30) UNIQUE NOT NULL,
    idTitulacion       NUMBER,
    CONSTRAINT pk_alumno PRIMARY KEY (idPersona),
    CONSTRAINT fk_alumno_persona FOREIGN KEY (idPersona)
        REFERENCES Persona (idPersona)
        ON DELETE CASCADE
);

-- Profesor
CREATE TABLE Profesor (
    idPersona        NUMBER,
    idDepartamento   NUMBER NOT NULL,
    dedicacion       VARCHAR2(50),
    CONSTRAINT pk_profesor PRIMARY KEY (idPersona),
    CONSTRAINT fk_profesor_persona FOREIGN KEY (idPersona)
        REFERENCES Persona (idPersona)
        ON DELETE CASCADE
);

-- Administrativo
CREATE TABLE Administrativo (
    idPersona             NUMBER,
    idUnidadAdministrativa NUMBER NOT NULL,
    categoriaProfesional  VARCHAR2(50),
    CONSTRAINT pk_administrativo PRIMARY KEY (idPersona),
    CONSTRAINT fk_adm_persona FOREIGN KEY (idPersona)
        REFERENCES Persona (idPersona)
        ON DELETE CASCADE
);

-- Tablas independientes
-- Centro Educativo
CREATE TABLE CentroEducativo (
    idCentro   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_centro PRIMARY KEY (idCentro)
);

-- Departamento
CREATE TABLE Departamento (
    idDepartamento  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (idDepartamento)
);

-- Títulos
CREATE TABLE Titulos (
    idTitulo  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_titulo PRIMARY KEY (idTitulo)
);

-- Unidad Administrativa
CREATE TABLE UnidadAdministrativa (
    idUnidadAdministrativa NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR2(150) NOT NULL,
    idCentroEducativo      NUMBER NOT NULL,
    CONSTRAINT pk_unidad_admin PRIMARY KEY (idUnidadAdministrativa),
    CONSTRAINT fk_unidad_centro FOREIGN KEY (idCentroEducativo)
        REFERENCES CentroEducativo (idCentro)
);

-- Tablas de relaciones
-- Relación N:M Profesor - CentroEducativo
CREATE TABLE Profesor_CentroEducativo (
    idProfesor       NUMBER NOT NULL,
    idCentroEducativo NUMBER NOT NULL,
    CONSTRAINT pk_prof_centro PRIMARY KEY (idProfesor, idCentroEducativo),
    CONSTRAINT fk_prof_centro_prof FOREIGN KEY (idProfesor)
        REFERENCES Profesor (idPersona),
    CONSTRAINT fk_prof_centro_centro FOREIGN KEY (idCentroEducativo)
        REFERENCES CentroEducativo (idCentro)
);

