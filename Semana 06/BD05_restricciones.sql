--Vista
CREATE OR REPLACE VIEW vPersonasUniversidad AS
SELECT 
    p.idPersona,
    p.nombre,
    p.apellido,
    p.dni,
    p.fecha_nac,
    'ALUMNO' AS tipoPersona,
    a.numExpediente AS dato1,
    ce.nombre AS centro_o_depto,
    t.nombre AS titulo_o_categoria
FROM Persona p
JOIN Alumno a ON p.idPersona = a.idPersona
LEFT JOIN CentroEducativo ce ON a.idCentroEducativo = ce.idCentro
LEFT JOIN Titulos t ON a.idTitulacion = t.idTitulo

UNION ALL

SELECT 
    p.idPersona,
    p.nombre,
    p.apellido,
    p.dni,
    p.fecha_nac,
    'PROFESOR' AS tipoPersona,
    pr.categoria AS dato1,
    d.nombre AS centro_o_depto,
    NULL AS titulo_o_categoria
FROM Persona p
JOIN Profesor pr ON p.idPersona = pr.idPersona
LEFT JOIN Departamento d ON pr.idDepartamento = d.idDepartamento

UNION ALL

SELECT 
    p.idPersona,
    p.nombre,
    p.apellido,
    p.dni,
    p.fecha_nac,
    'ADMINISTRATIVO' AS tipoPersona,
    ad.cargo AS dato1,
    ua.nombre AS centro_o_depto,
    NULL AS titulo_o_categoria
FROM Persona p
JOIN Administrativo ad ON p.idPersona = ad.idPersona
LEFT JOIN UnidadAdministrativa ua ON ad.idUnidadAdministrativa = ua.idUnidadAdministrativa
ORDER BY apellido, nombre;

