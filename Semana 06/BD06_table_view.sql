-- Creación de la tabla EMPLEADOS
CREATE TABLE EMPLEADOS (
    DNI             NUMBER(8) PRIMARY KEY,
    NOMBRE          VARCHAR(10) NOT NULL,
    APELLIDO1       VARCHAR(15) NOT NULL,
    APELLIDO2       VARCHAR(15),
    DIRECC1         VARCHAR(25),
    DIRECC2         VARCHAR(20),
    CIUDAD          VARCHAR(20),
    PROVINCIA       VARCHAR(20),
    COD_POSTAL      VARCHAR(5),
    SEXO            VARCHAR(1),
    FECHA_NAC       DATE
);

-- Creación de la tabla DEPARTAMENTOS
CREATE TABLE DEPARTAMENTOS (
    DPTO_COD        NUMBER(5) PRIMARY KEY,
    NOMBRE_DPTO     VARCHAR(30) NOT NULL,
    DPTO_PADRE      NUMBER(5),
    PRESUPUESTO     NUMBER NOT NULL,
    PRES_ACTUAL     NUMBER,
    FOREIGN KEY (DPTO_PADRE) REFERENCES DEPARTAMENTOS(DPTO_COD)
);

-- Creación de la tabla UNIVERSIDADES
CREATE TABLE UNIVERSIDADES (
    UNIV_COD        NUMBER(5) PRIMARY KEY,
    NOMBRE_UNIV     VARCHAR(25) NOT NULL,
    CIUDAD          VARCHAR(20),
    MUNICIPIO       VARCHAR(2),
    COD_POSTAL      VARCHAR(5)
);

-- Creación de la tabla ESTUDIOS
CREATE TABLE ESTUDIOS (
    EMPLEADO_DNI    NUMBER(8) NOT NULL,
    UNIVERSIDAD     NUMBER(5) NOT NULL,
    AÑO             NUMBER,
    GRADO           VARCHAR(3),
    ESPECIALIDAD    VARCHAR(20),
    PRIMARY KEY (EMPLEADO_DNI, UNIVERSIDAD),
    FOREIGN KEY (EMPLEADO_DNI) REFERENCES EMPLEADOS(DNI),
    FOREIGN KEY (UNIVERSIDAD) REFERENCES UNIVERSIDADES(UNIV_COD)
);

-- Creación de la tabla TRABAJOS
CREATE TABLE TRABAJOS (
    TRABAJO_COD     NUMBER(5) PRIMARY KEY,
    NOMBRE_TRAB     VARCHAR(20) NOT NULL,
    SALARIO_MIN     NUMBER(2) NOT NULL,
    SALARIO_MAX     NUMBER(2) NOT NULL
);

-- Creación de la tabla HISTORIAL_LABORAL
CREATE TABLE HISTORIAL_LABORAL (
    EMPLEADO_DNI    NUMBER(8) NOT NULL,
    TRABAJO_COD     NUMBER(5) NOT NULL,
    FECHA_INICIO    DATE NOT NULL,
    FECHA_FIN       DATE,
    DPTO_COD        NUMBER(5),
    SUPERVISOR_DNI  NUMBER(8),
    PRIMARY KEY (EMPLEADO_DNI, TRABAJO_COD, FECHA_INICIO),
    FOREIGN KEY (EMPLEADO_DNI) REFERENCES EMPLEADOS(DNI),
    FOREIGN KEY (TRABAJO_COD) REFERENCES TRABAJOS(TRABAJO_COD),
    FOREIGN KEY (DPTO_COD) REFERENCES DEPARTAMENTOS(DPTO_COD),
    FOREIGN KEY (SUPERVISOR_DNI) REFERENCES EMPLEADOS(DNI)
);

-- Creación de la tabla HISTORIAL_SALARIAL
CREATE TABLE HISTORIAL_SALARIAL (
    EMPLEADO_DNI    NUMBER(8) NOT NULL,
    SALARIO         NUMBER NOT NULL,
    FECHA_COMIENZO  DATE NOT NULL,
    FECHA_FIN       DATE,
    PRIMARY KEY (EMPLEADO_DNI, FECHA_COMIENZO),
    FOREIGN KEY (EMPLEADO_DNI) REFERENCES EMPLEADOS(DNI)
);

