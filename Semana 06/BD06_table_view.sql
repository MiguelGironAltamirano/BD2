--18.-
CREATE VIEW INFORMACION_EMPLEADOS AS
SELECT
    NOMBRE || ' ' || APELLIDO1 || ' ' || APELLIDO2 AS NOMBRE_COMPLETO,
    TRUNC(MONTHS_BETWEEN(SYSDATE, FECHA_NAC) / 12) AS EDAD
FROM
    EMPLEADOS;

--19.-
CREATE OR REPLACE VIEW INFORMACION_ACTUAL AS
SELECT
    ie.NOMBRE_COMPLETO,
    ie.EDAD,
    hs.SALARIO
FROM
    INFORMACION_EMPLEADOS ie
JOIN EMPLEADOS e
    ON ie.NOMBRE_COMPLETO = (e.NOMBRE || ' ' || e.APELLIDO1 || ' ' || e.APELLIDO2)
JOIN (
    SELECT EMPLEADO_DNI, SALARIO
    FROM (
        SELECT 
            EMPLEADO_DNI,
            SALARIO,
            ROW_NUMBER() OVER (PARTITION BY EMPLEADO_DNI ORDER BY FECHA_COMIENZO DESC) AS rn
        FROM HISTORIAL_SALARIAL
    )
    WHERE rn = 1
) hs
    ON e.DNI = hs.EMPLEADO_DNI;
