INSERT INTO INFORMACION_UNIVERSITARIA (NOMBRE_COMPLETO, UNIVERSIDAD_NOMBRE)
SELECT
    e.NOMBRE || ' ' || e.APELLIDO1 || ' ' || e.APELLIDO2 AS NOMBRE_COMPLETO,
    u.NOMBRE_UNIV AS UNIVERSIDAD_NOMBRE
FROM
    EMPLEADOS e
JOIN
    ESTUDIOS es ON e.DNI = es.EMPLEADO_DNI
JOIN
    UNIVERSIDADES u ON es.UNIVERSIDAD = u.UNIV_COD;
    
